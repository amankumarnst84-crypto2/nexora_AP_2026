-- WashTrack PostgreSQL schema
-- Based on dbms/01_normalization.md. Proposed schema; verify identifiers
-- against the application's Prisma models before using as a production migration.

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_identifier TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('STUDENT', 'STAFF')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_login_identifier_nonblank CHECK (length(btrim(login_identifier)) > 0),
    CONSTRAINT users_full_name_nonblank CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT users_password_hash_nonblank CHECK (length(btrim(password_hash)) > 0)
);

CREATE TABLE students (
    user_id BIGINT PRIMARY KEY REFERENCES users(user_id) ON DELETE RESTRICT,
    bag_number TEXT NOT NULL UNIQUE,
    CONSTRAINT students_bag_number_nonblank CHECK (length(btrim(bag_number)) > 0)
);

CREATE TABLE clothing_types (
    clothing_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT clothing_types_name_nonblank CHECK (length(btrim(name)) > 0)
);

CREATE TABLE washing_lots (
    lot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wash_date DATE NOT NULL,
    shift TEXT NOT NULL CHECK (shift IN ('MORNING', 'EVENING'))
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bag_number TEXT NOT NULL REFERENCES students(bag_number) ON DELETE RESTRICT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    current_status TEXT NOT NULL DEFAULT 'SUBMITTED'
        CHECK (current_status IN ('SUBMITTED', 'RECEIVED', 'WASHING', 'READY', 'COLLECTED')),
    lot_id BIGINT REFERENCES washing_lots(lot_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX orders_one_active_order_per_bag
    ON orders (bag_number)
    WHERE current_status <> 'COLLECTED';

CREATE TABLE order_items (
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    clothing_type_id BIGINT NOT NULL REFERENCES clothing_types(clothing_type_id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 15),
    PRIMARY KEY (order_id, clothing_type_id)
);

CREATE TABLE order_status_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    event_sequence INTEGER NOT NULL CHECK (event_sequence > 0),
    status TEXT NOT NULL CHECK (status IN ('SUBMITTED', 'RECEIVED', 'WASHING', 'READY', 'COLLECTED')),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT order_status_events_order_sequence_unique UNIQUE (order_id, event_sequence)
);

CREATE TABLE order_delays (
    delay_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    staff_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    reason TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT order_delays_reason_nonblank CHECK (length(btrim(reason)) > 0)
);

CREATE TABLE complaints (
    complaint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    category TEXT NOT NULL CHECK (category IN ('MISSING_CLOTHES', 'EXTRA_CLOTHES', 'STAINS', 'COLOUR_DAMAGE')),
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT complaints_description_nonblank CHECK (length(btrim(description)) > 0)
);

CREATE TABLE complaint_responses (
    response_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id BIGINT NOT NULL REFERENCES complaints(complaint_id) ON DELETE RESTRICT,
    staff_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    response_text TEXT NOT NULL,
    responded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT complaint_responses_text_nonblank CHECK (length(btrim(response_text)) > 0),
    CONSTRAINT complaint_responses_complaint_response_unique UNIQUE (complaint_id, response_id)
);

CREATE TABLE complaint_confirmations (
    complaint_id BIGINT PRIMARY KEY REFERENCES complaints(complaint_id) ON DELETE RESTRICT,
    response_id BIGINT NOT NULL UNIQUE,
    confirmed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT complaint_confirmations_response_same_complaint_fk
        FOREIGN KEY (complaint_id, response_id)
        REFERENCES complaint_responses(complaint_id, response_id)
        ON DELETE RESTRICT
);

